// The executing recovery skill: the agent acts ONLY through the gated executor.
function writeRecoverySkill(profileDir, profileName, company) {
  const dir = path.join(profileDir, "skills", "revenue-recovery");
  fs.mkdirSync(dir, { recursive: true });
  const body = `---
name: revenue-recovery
description: The recovery loop for ${company || "this client"} — detect unpaid invoices, draft outreach in their voice/SOP, and (only through the gated executor) send and follow up to payment. Use for any "work the book / chase invoices / send the next batch / draft a reminder" task.
---

# Revenue recovery — execution (gated)

You recover ${company || "the client"}'s overdue invoices. Follow SOUL.md for voice, SOP, approval model, and the safety rails.

## The ONE rule that cannot be broken
You do NOT contact customers directly. You never call an email/SMS/payment/mail API yourself. Every outbound action goes through the executor:

\`\`\`
~/rrd-recover send ${profileName} '<action-json>'      # gate + send (if allowed)
~/rrd-recover gate ${profileName} '<action-json>'      # dry check only, sends nothing
\`\`\`

The executor enforces, in CODE: consent, allowed channels, the approval gate, the do-not-contact list, the discount cap, sending hours, stop-on-reply, batch size, and daily spend/volume caps. If it returns \`allowed:false\`, the action is queued for a human — do not try to route around it.

## Loop
1. Detect unpaid invoices in the client's payment/accounting system (read-only).
2. Pull the customer + postal address from the CRM.
3. Draft the message/letter in the voice and SOP from SOUL.md.
4. Submit it: \`~/rrd-recover send ${profileName} '{"channel":"Email","to":{...},"approved":<bool>,"atHour":<0-23>, ...}'\`.
5. On agreement, generate a payment link (through the executor).
6. Letters: always approval-gated; the formal-demand rung goes certified. They post via the client's own PostGrid account.
7. Report outcomes to the primary contact weekly.

Your allowed tools are fixed (see manifest.json \`toolAllowlist\`): read payments, read CRM, draft, queue, send-via-executor, generate-payment-link. Nothing else.
`;
  fs.writeFileSync(path.join(dir, "SKILL.md"), body, "utf8");
  console.log("  ✓ wrote " + path.join(dir, "SKILL.md"));
}

// Publish this client's vault PUBLIC key to Supabase so the serverless self-serve
// OAuth connect (Vercel) can mint connect links. The matching PRIVATE key is created
// and kept on this Mac — zero-knowledge is preserved (only the public key is uploaded).
async function publishVaultPublicKey(submissionId, profileName) {
  if (!URL_BASE || !KEY) throw new Error("Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY.");
  const { publicKeyPem } = loadOrCreateKeypair(profileName);
  const res = await fetch(`${URL_BASE}/rest/v1/vault_public_keys`, {
    method: "POST",
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, "Content-Type": "application/json", Prefer: "resolution=merge-duplicates,return=minimal" },
    body: JSON.stringify({ submission_id: submissionId, profile: profileName, public_key: publicKeyPem, updated_at: new Date().toISOString() }),
  });
  if (!res.ok) throw new Error(`vault_public_keys upsert ${res.status}: ${await res.text()}`);
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help || !opts.id) { usage(); process.exit(opts.id ? 0 : 1); }

  const rec = await fetchSubmission(opts.id);
  const pack = buildHermesPack(rec);

  console.log(`\nHermes profile pack for: ${pack.manifest.company}`);
  console.log(`Profile name: ${pack.profileName}`);
  console.log(`API-key secrets still needed (send a vault link): ${pack.manifest.envKeysNeeded.join(", ") || "(none yet)"}`);
  console.log(`OAuth connections to set up (connect flow, NOT the vault): ${(pack.manifest.oauthConnectionsNeeded || []).join(", ") || "(none)"}`);
  console.log(`Composio-managed connections to authorize: ${(pack.manifest.composioConnectionsNeeded || []).join(", ") || "(none)"}`);
  console.log(`Readiness: integrationReady=${pack.manifest.readiness.integrationReady}, hasSop=${pack.manifest.readiness.hasSop}, consent=${pack.manifest.readiness.consent}\n`);

  if (opts.dryRun) {
    console.log("── SOUL.md ──\n" + pack.soul + "\n");
    console.log("── memories/MEMORY.md (" + pack.memory.length + "/2200) ──\n" + pack.memory + "\n");
    console.log("── memories/USER.md (" + pack.user.length + "/1375) ──\n" + pack.user + "\n");
    console.log("── manifest.json ──\n" + JSON.stringify(pack.manifest, null, 2));
    console.log("\n(dry run — nothing written)");
    return;
  }

  // resolve target profile directory
  let profileDir;
  if (opts.out) {
    profileDir = path.join(path.resolve(opts.out), pack.profileName);
  } else {
    const hermesProfiles = path.join(OPERATOR_HOME, ".hermes", "profiles");
    profileDir = path.join(hermesProfiles, pack.profileName);
    if (!opts.noCli) {
      try {
        execFileSync("hermes", ["profile", "create", pack.profileName], { stdio: "ignore" });
        console.log("  ✓ hermes profile create " + pack.profileName);
      } catch (e) {
        console.log("  • `hermes profile create` skipped (" + (e.code || "unavailable") + ") — writing files directly.");
      }
    }
  }

  fs.mkdirSync(path.join(profileDir, "memories"), { recursive: true });
  console.log("Writing pack into: " + profileDir);
  writeFileSafe(path.join(profileDir, "SOUL.md"), pack.soul, opts.force);
  writeFileSafe(path.join(profileDir, "memories", "MEMORY.md"), pack.memory, opts.force);
  writeFileSafe(path.join(profileDir, "memories", "USER.md"), pack.user, opts.force);
  writeFileSafe(path.join(profileDir, "manifest.json"), JSON.stringify(pack.manifest, null, 2), true);
  writeHermesRuntimeConfig(profileDir, pack.manifest);
  writeEnvTemplate(path.join(profileDir, ".env"), pack.manifest.envKeysNeeded);

  // Per-client cloud desktop: drop the computer-use skill always; provision the
  // live Orgo project only for real profiles (not --out previews).
  if (!opts.noOrgo) {
    writeComputerUseSkill(profileDir, pack.profileName, pack.manifest.company);
    if (!opts.out) provisionOrgo(pack.profileName, pack.manifest.company);
  }

  // Guardrails: freeze the client's policy next to the agent so the executor enforces it offline,
  // and drop the gated recovery skill.
  writeFileSafe(path.join(profileDir, "policy.json"), JSON.stringify(buildPolicy(rec), null, 2), true);
  writeRecoverySkill(profileDir, pack.profileName, pack.manifest.company);

  // Publish the vault public key so clients can self-serve OAuth connect (e.g. Google
  // Workspace) from the dashboard. Non-fatal: provisioning still succeeds if this fails.
  if (!opts.out) {
    try {
      await publishVaultPublicKey(opts.id, pack.profileName);
      console.log("  ✓ published vault public key for serverless connect");
    } catch (e) {
      console.log("  • vault public key publish skipped (" + ((e && e.message) || e) + ") — run `rrd-vault publish-key " + opts.id + "` later.");
    }
  }

  console.log("\nNext steps:");
  console.log("  1. Fill the .env secrets securely (Stripe/CRM/email keys) and install any Composio connected-account ids from the Composio authorization flow.");
  console.log("  2. Create/assign the FlowAudit-managed ChatGPT Plus/Pro account for this client agent, then run:  /Users/AIAgenterminal/rrd-agent-llm auth " + pack.profileName);
  console.log("  3. Verify model auth without printing tokens:  /Users/AIAgenterminal/rrd-agent-llm status " + pack.profileName);
  console.log("  4. Review SOUL.md — it encodes their approval rules, do-not-contact list, and SOP.");
  console.log("  5. Run the minimum-ready smoke test:  /Users/AIAgenterminal/rrd-ready check " + pack.profileName + " --allow-no-orgo");
  console.log("  6. Start the gateway after the smoke test passes:  hermes --profile " + pack.profileName + " gateway run --replace");
  console.log("  7. The recovery skill drops into " + path.join(profileDir, "skills", "revenue-recovery", "SKILL.md"));
}

main().catch((e) => { console.error("Error: " + (e && e.message || e)); process.exit(1); });
