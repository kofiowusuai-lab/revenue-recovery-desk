#!/usr/bin/env node
/**
 * hermes-provision.mjs — turn an onboarding submission into a Hermes profile.
 *
 * Pulls a submission from Supabase (service-role), builds the Hermes profile
 * pack (SOUL.md + memories/MEMORY.md + memories/USER.md + manifest.json), and
 * writes it into a new profile at ~/.hermes/profiles/<profile>/.
 *
 *   export SUPABASE_URL="https://YOUR-REF.supabase.co"
 *   export SUPABASE_SERVICE_ROLE_KEY="service-role-secret"
 *
 *   node hermes-provision.mjs --dry-run <submission-id>     # preview, write nothing
 *   node hermes-provision.mjs <submission-id>               # create profile + write files
 *   node hermes-provision.mjs --out /tmp/packs <id>         # write to a dir (no Hermes CLI)
 *   node hermes-provision.mjs --no-cli <id>                 # write files, skip `hermes profile create`
 *   node hermes-provision.mjs --force <id>                  # overwrite existing SOUL/MEMORY/USER
 *
 * SAFETY: this never writes or prints secret values. The .env it creates holds
 * only EMPTY placeholders for the keys you must fill in securely, and it will
 * NEVER overwrite an existing .env.
 */

import { rowToRecord, buildHermesPack } from "./rrd-hermes.mjs";
import { buildPolicy } from "./rrd-guardrails.mjs";
import { loadOrCreateKeypair } from "./rrd-vault-fs.mjs";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
const OPERATOR_HOME = process.env.RRD_OPERATOR_HOME || "/Users/AIAgenterminal";
import { execFileSync } from "node:child_process";

const URL_BASE = (process.env.SUPABASE_URL || "").replace(/\/+$/, "");
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_KEY || "";

function parseArgs(argv) {
  const opts = { dryRun: false, noCli: false, force: false, out: null, id: null, noOrgo: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--dry-run") opts.dryRun = true;
    else if (a === "--no-cli") opts.noCli = true;
    else if (a === "--no-orgo") opts.noOrgo = true;
    else if (a === "--force") opts.force = true;
    else if (a === "--out") opts.out = argv[++i];
    else if (a === "-h" || a === "--help") opts.help = true;
    else if (!a.startsWith("--")) opts.id = a;
  }
  return opts;
}
function usage() {
  console.error(`hermes-provision — onboarding submission → Hermes profile

Usage: node hermes-provision.mjs [--dry-run] [--out <dir>] [--no-cli] [--force] <submission-id>

Env:   SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY`);
}

async function fetchSubmission(id) {
  if (!URL_BASE || !KEY) throw new Error("Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (Supabase → Settings → API).");
  const res = await fetch(`${URL_BASE}/rest/v1/submissions?id=eq.${encodeURIComponent(id)}&select=*`, {
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}` }
  });
  if (!res.ok) throw new Error(`Supabase ${res.status}: ${await res.text()}`);
  const rows = await res.json();
  if (!rows || !rows.length) throw new Error("No submission found with id " + id);
  return rowToRecord(rows[0]);
}

function writeFileSafe(file, content, force) {
  if (fs.existsSync(file) && !force) {
    fs.copyFileSync(file, file + ".bak");
    console.log("  • backed up existing " + path.basename(file) + " → " + path.basename(file) + ".bak");
  }
  fs.writeFileSync(file, content, "utf8");
  console.log("  ✓ wrote " + file + "  (" + content.length + " chars)");
}

function writeEnvTemplate(file, keys) {
  if (fs.existsSync(file)) {
    console.log("  • .env already exists — NOT touching it (it may hold real secrets).");
    console.log("    Ensure these keys are present and filled: " + (keys.length ? keys.join(", ") : "(none)"));
    return;
  }
  const body = [
    "# Revenue-recovery integration secrets for this Hermes profile.",
    "# Fill these in securely. NEVER commit this file.",
    ""
  ].concat(keys.map((k) => k + "=")).join("\n") + "\n";
  fs.writeFileSync(file, body, "utf8");
  console.log("  ✓ wrote " + file + "  (" + keys.length + " empty placeholder(s))");
}

function writeHermesRuntimeConfig(profileDir, manifest) {
  const runtime = manifest.llmRuntime || {};
  const provider = runtime.provider || "openai-codex";
  const model = runtime.model || "gpt-5.1-codex-max";
  const configPath = path.join(profileDir, "config.yaml");
  const body = [
    "# Generated by hermes-provision.mjs for a client-isolated Revenue Recovery agent.",
    "# Secrets and OAuth tokens do NOT live here. ChatGPT OAuth is profile-local in auth.json.",
    "model:",
    `  provider: ${provider}`,
    `  default: ${model}`,
    "  openai_runtime: auto",
    "agent:",
    "  max_turns: 90",
    "terminal:",
    "  cwd: /Users/AIAgenterminal",
    "rrd:",
    "  llm_runtime:",
    "    mode: flowaudit_managed_chatgpt",
    "    provider: openai-codex",
    `    model: ${model}`,
    "    account_owner: FlowAudit",
    "    auth_store: auth.json",
    "    status: pending_oauth",
    ""
  ].join("\n");
  if (fs.existsSync(configPath)) {
    const existing = fs.readFileSync(configPath, "utf8");
    if (/provider:\s*openai-codex/.test(existing) && existing.includes("rrd:")) {
      console.log("  • config.yaml already has RRD ChatGPT runtime — leaving it in place.");
      return;
    }
    fs.copyFileSync(configPath, configPath + ".bak");
    console.log("  • backed up existing config.yaml → config.yaml.bak");
  }
  fs.writeFileSync(configPath, body, "utf8");
  console.log("  ✓ wrote " + configPath + "  (ChatGPT/Codex runtime pending OAuth)");
}

// On-demand Orgo project for this client (best-effort; needs ORGO_API_KEY in ~/.openclaw/.env).
// Creates the persistent project only — no running desktop, so no cost until a recovery run.
function provisionOrgo(profileName, company) {
  const wrapper = path.join(OPERATOR_HOME, "rrd-orgo");
  if (!fs.existsSync(wrapper)) { console.log("  • Orgo: rrd-orgo not found — skipping cloud-desktop provisioning."); return; }
  try {
    const args = ["provision", profileName];
    if (company) args.push("--company", company);
    const o = execFileSync(wrapper, args, { encoding: "utf8" });
    const r = JSON.parse(o);
    console.log("  ✓ Orgo project ready: " + (r.projectId || "?") + (r.created ? " (created)" : " (existing)") + " — on-demand, no desktop running.");
  } catch (e) {
    const msg = (e && e.stdout) ? String(e.stdout).trim() : (e && e.message) || String(e);
    console.log("  • Orgo provisioning skipped: " + msg.split("\n").slice(-1)[0]);
  }
}

